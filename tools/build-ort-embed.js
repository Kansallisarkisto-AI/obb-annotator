/* Regenerates vendor/ort/ort-wasm-embedded.js from an npm install of onnxruntime-web.
 *
 *   npm install onnxruntime-web@1.22.0
 *   node tools/build-ort-embed.js node_modules/onnxruntime-web/dist
 *
 * Why: the ORT WebAssembly glue is an ES module and the .wasm is normally fetch()ed.
 * Both are blocked for pages opened from file://, so the app embeds them in a classic
 * script (window.__ORT_EMBED) that is loaded lazily the first time detection is used,
 * then hands ORT a blob: URL for the glue and the wasm bytes directly.
 * Also copy ort.wasm.min.js from the same dist folder into vendor/ort/.
 */
var fs = require("fs"), path = require("path");
var dist = process.argv[2] || "node_modules/onnxruntime-web/dist";
var out = path.join(__dirname, "..", "vendor", "ort", "ort-wasm-embedded.js");
var mjs = fs.readFileSync(path.join(dist, "ort-wasm-simd-threaded.mjs"), "utf8");
// The glue computes  new URL("ort-wasm-simd-threaded.wasm", import.meta.url)  as a fallback location
// even when the wasm bytes are supplied via env.wasm.wasmBinary. When the module is loaded from a
// blob: URL that throws "Invalid URL" (a blob: base can't resolve relative paths). The value is
// never used in our setup, so neutralise it.
var needle = 'new URL("ort-wasm-simd-threaded.wasm",import.meta.url)';
if (mjs.split(needle).length !== 2) throw new Error("Expected exactly one occurrence of the wasm URL fallback; the ORT glue changed -- re-check this patch.");
mjs = mjs.replace(needle, '({href:"ort-wasm-simd-threaded.wasm"})');
var wasm = fs.readFileSync(path.join(dist, "ort-wasm-simd-threaded.wasm"));
fs.writeFileSync(out,
  "/* generated by tools/build-ort-embed.js -- onnxruntime-web WASM runtime (MIT) */\n" +
  "window.__ORT_EMBED = {\n  mjs: " + JSON.stringify(mjs) + ",\n  wasmB64: \"" + wasm.toString("base64") + "\"\n};\n");
console.log("wrote", out, (fs.statSync(out).size / 1048576).toFixed(1) + " MB");
